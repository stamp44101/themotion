/** point in polygon (even-odd) */
export const inPoly = (pts: P[], x: number, z: number) => {
  let c = false;
  for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
    const [xi, zi] = pts[i];
    const [xj, zj] = pts[j];
    if (zi > z !== zj > z && x < ((xj - xi) * (z - zi)) / (zj - zi) + xi) c = !c;
  }
  return c;
};
export const inWater = (x: number, z: number) => WATERS.some((w) => inPoly(w.outer, x, z) && !w.holes.some((h) => inPoly(h, x, z)));
/** trees never stand on the water: a 2-unit grid of clearings over the estuary and the sea */
export const WATER_CLEARINGS: [number, number, number, number][] = (() => {
  const out: [number, number, number, number][] = [];
  for (let x = TILE.x0 + 1; x < TILE.x1; x += 2)
    for (let z = TILE.z0 + 1; z < TILE.z1; z += 2) if (inWater(x, z)) out.push([x, z, 1.55, -1e9]);
  return out;
})();

